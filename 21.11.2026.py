# Замените все русские и английские гласные обоих регистров на *.
# Гласные: аеёиоуыэюя и aeiou. Остальные символы сохраняются.
# Используйте str.maketrans() и translate().
# Ответ: одна строка — результат.
# Данные для ответа:
# В ответе запишите значение, которое получится, если пользователь введёт Ёлка.
n = input()
value = "аеёиоуыэюяАЕЁИОУЫЭЮЯaeiouAEIOU"
max_value = 0
for i in value:
    place = n.rfind(i)
    if place > max_value:
        max_value = place
print(max_value)



