# Найдите их наименьшее общее кратное (НОК) — наименьшее положительное число, делящееся без остатка на A и B.
# Перебирайте кратные большего числа с помощью while. Готовые функции вычисления НОК и НОД использовать нельзя.
# Ответ: одно целое число — НОК.
# Данные для ответа:
# В ответе запишите значение, которое получится, если пользователь введёт 8, затем 12. Каждое значение вводится с новой строки.
A = int(input())
B = int(input())
if A > B:
    result = A
else:
    result = B
while result <= 1000 and (result % A != 0 or result % B != 0):
    result += 1
print(result)
