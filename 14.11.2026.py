# Пользователь вводит непустое слово без пробелов.
# Переберите все срезы длиной 3 и посчитайте те, которые читаются одинаково слева направо и справа налево.
# Перекрывающиеся срезы учитываются отдельно. Если длина слова меньше 3, результат равен 0.
# Ответ: одно целое число — количество подходящих срезов.
counter = 0
s = input()
for i in range(len(s)):
    srez = s[i:i + 3]
    if srez == srez[::-1]:
        counter += 1
print(counter)
